export function describeExperience(experience: ExperienceInput): string {
  const period =
    experience.kind === "certificate"
      ? (experience.startMonth ?? "없음")
      : `${experience.startMonth ?? "없음"} ~ ${experience.isOngoing ? "진행 중" : (experience.endMonth ?? "없음")}`;
  const metrics =
    experience.metrics.length === 0
      ? "없음"
      : experience.metrics.map((m, i) => `${i + 1}. ${m.text} (기준·근거: ${m.basis ?? "없음"})`).join("\n");
  const lines: [string, string | null][] = [
    ["이름", experience.name],
    ["구분", KIND_LABELS[experience.kind]],
    ["소속·기관", experience.organization],
    ["직무·역할", experience.role],
    ["기간", period],
    ["상황", experience.situation],
    ["본인이 한 일", experience.actions],
    ["결과", experience.result],
    ["수치", metrics],
    ["하지 않은 것", experience.notDone],
    ["증빙·확인 메모", experience.evidenceNote],
  ];
  return lines.map(([label, value]) => `[${label}]\n${value ?? "없음"}`).join("\n\n");
}

// 장면을 판정할 글. 머리(회사·프로젝트·활동)의 이름 칸과 판정에 쓸 기간을 함께 준다.
// 금지 표현은 보내지 않는다(증빙 메모는 describeExperience처럼 보낸다)
export function describeScene(scene: SceneInput, head: SceneHead): string {
  const range = scene.startMonth === null ? head.period : scene;
  const period = `${range.startMonth ?? "없음"} ~ ${range.isOngoing ? "진행 중" : (range.endMonth ?? "없음")}`;
  const periodNote = scene.startMonth === null ? `${period} (머리의 기간)` : period;
  const metrics =
    scene.metrics.length === 0
      ? "없음"
      : scene.metrics.map((m, i) => `${i + 1}. ${m.text} (기준·근거: ${m.basis ?? "없음"})`).join("\n");
  const lines: [string, string | null][] = [
    ...head.labels,
    ["장면 제목", scene.title],
    ["기간", periodNote],
    ["상황", scene.situation],
    ["판단", scene.judgment],
    ["본인이 한 일", scene.actions],
    ["결과", scene.result],
    ["배운 점", scene.lessons],
    ["수치", metrics],
    ["하지 않은 것", scene.notDone],
    ["증빙·확인 메모", scene.evidenceNote],
  ];
  return lines.map(([label, value]) => `[${label}]\n${value ?? "없음"}`).join("\n\n");
}

